  @translations %{
    "en" => @english,
    "pt" => @portuguese,
    "es" => @spanish,
    "fr" => @french,
    "de" => @german,
    "it" => @italian,
    "nl" => @dutch,
    "ja" => @japanese
  }

  english_keys = @english |> Map.keys() |> MapSet.new()

  for {lang, messages} <- @translations do
    keys = messages |> Map.keys() |> MapSet.new()

    unless MapSet.equal?(keys, english_keys) do
      missing = english_keys |> MapSet.difference(keys) |> Enum.sort()
      extra = keys |> MapSet.difference(english_keys) |> Enum.sort()

      raise CompileError,
        description:
          "#{inspect(__MODULE__)}: #{lang} keys differ from English " <>
            "(missing: #{inspect(missing)}, extra: #{inspect(extra)})"
    end
  end

  @spec english() :: %{String.t() => String.t()}
  def english, do: @english

  @spec all() :: %{String.t() => %{String.t() => String.t()}}
  def all, do: @translations
