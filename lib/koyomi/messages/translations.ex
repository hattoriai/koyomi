  # gender (pt: segunda-feira is feminine, sábado and domingo masculine; it:
  # domenica is feminine), the template hangs the ordinal on "week" instead:
  # "Na primeira semana, domingo". The nth occurrence of a weekday always falls
  # in days 7(n-1)+1 to 7n, so "the first week" (days 1 to 7) reads the same
  # rule. es, fr, de and nl weekdays share one gender, so they agree directly.
  # ja reads "毎月第1月曜日" and "毎月最終月曜日".

